// Wraps @hashgraphonline/standards-sdk for HCS-14 Universal Agent IDs and
// (optionally) HCS-11 agent-profile publication.
//
// HCS-14 UAID format (HOL spec):
//   uaid:did:hedera:<network>:<base58key>_<didTopicId>;
//     uid=<uuid>;proto=hcs-10;nativeId=hedera:<network>:<accountId>
//
// The simple "uaid from existing did:hedera" path is synchronous and depends
// only on the DID string + routing params — no HCS topics needed. The full
// HCS-11 profile publication is broken out separately because it requires a
// funded operator and is the slowest part of bootstrap.

import { createUaid } from '@hashgraphonline/standards-sdk';

/**
 * Wrap a `did:hedera` URI in an HCS-14 UAID with routing params.
 *
 * Pure function — no network calls. Use this when the agent's DID already
 * exists and you just need the UAID for memos / discovery.
 *
 * @param {string} did                          A `did:hedera:...` URI.
 * @param {object} [params]
 * @param {string} [params.proto]               Default 'hcs-10' (agent comms protocol).
 * @param {string} [params.nativeId]            E.g. `hedera:testnet:0.0.12345`.
 * @param {string} [params.uid]                 Optional UUID; auto-generated by createUaid if omitted.
 * @param {string} [params.registry]            Optional registry hint.
 * @returns {string} UAID string
 */
export function buildUaidFromDid(did, params = {}) {
  if (!did) throw new Error('buildUaidFromDid: did required');
  return createUaid(did, params);
}
